#!/usr/bin/env python3
"""
Setup WhatsApp Keep-Alive Ping (Heartbeat) Cron
================================================
Menjaga sesi WhatsApp di Wameow agar selalu terhubung dan tidak terputus (disconnected)
dengan mengirimkan sinyal ping otomatis setiap tengah malam (pukul 00:00 WIB).

Fitur:
- Deteksi sesi Wameow aktif di http://localhost:52135
- Pilihan target pengiriman ping:
  1. Grup khusus (misal: "Ping Connection", "Arsip Pribadi", atau grup uji coba)
  2. Chat ke nomor sendiri (Saved Messages / Self-Chat: <phone>@s.whatsapp.net)
- Uji coba (test ping) langsung untuk memastikan pengiriman sukses
- Otomatis membuat script ~/.hermes/scripts/wameow-ping.sh
- Otomatis mendaftarkan jadwal cron harian jam 00:00 WIB (Hermes Cron / Crontab)

Usage:
    python3 setup_keepalive.py [--target-jid JID] [--auto]
"""

import os
import sys
import json
import argparse
import subprocess
import urllib.request
import urllib.error

HOME = os.path.expanduser("~")
HERMES_DIR = os.path.join(HOME, ".hermes")
SCRIPTS_DIR = os.path.join(HERMES_DIR, "scripts")
PING_SCRIPT_PATH = os.path.join(SCRIPTS_DIR, "wameow-ping.sh")
WAMEOW_URL = os.environ.get("WAMEOW_BASE_URL", "http://localhost:52135")


def fetch_api(endpoint):
    url = f"{WAMEOW_URL.rstrip('/')}{endpoint}"
    req = urllib.request.Request(url, headers={"User-Agent": "Wameow-Setup"})
    with urllib.request.urlopen(req, timeout=5) as resp:
        return json.loads(resp.read().decode("utf-8"))


def test_ping(base_url=WAMEOW_URL):
    url = f"{base_url.rstrip('/')}/ping"
    req = urllib.request.Request(url, data=b"", headers={"User-Agent": "Wameow-Setup"}, method="POST")
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            return data
    except Exception as e:
        return {"error": True, "message": str(e)}


def create_ping_script():
    os.makedirs(SCRIPTS_DIR, exist_ok=True)
    script_content = """#!/usr/bin/env bash
# Wameow Keep-Alive Midnight Ping Script
# Auto-generated by setup_keepalive.py

BASE_URL="${WAMEOW_BASE_URL:-http://localhost:52135}"

for i in 1 2 3; do
  resp=$(curl -s -X POST "${BASE_URL}/ping" 2>/dev/null)
  if echo "$resp" | grep -q '"status":"ok"'; then
    echo "[OK] Ping sent successfully: $resp"
    exit 0
  fi
  sleep 10
done

echo "[FAIL] Ping failed after 3 attempts: $resp"
exit 1
"""
    with open(PING_SCRIPT_PATH, "w") as f:
        f.write(script_content)
    os.chmod(PING_SCRIPT_PATH, 0o755)
    print(f"✅ Script ping tersimpan di: {PING_SCRIPT_PATH}")


def register_hermes_cron():
    jobs_file = os.path.join(HERMES_DIR, "cron", "jobs.json")
    if not os.path.isfile(jobs_file):
        return False

    try:
        with open(jobs_file, "r") as f:
            data = json.load(f)

        is_dict_wrapper = isinstance(data, dict) and "jobs" in data
        job_list = data.get("jobs", data) if is_dict_wrapper else data

        # Check if already exists
        if isinstance(job_list, dict):
            for k, j in job_list.items():
                if j.get("name") == "wameow-ping":
                    print("ℹ️  Cronjob 'wameow-ping' sudah terdaftar di Hermes.")
                    return True
        elif isinstance(job_list, list):
            for j in job_list:
                if j.get("name") == "wameow-ping":
                    print("ℹ️  Cronjob 'wameow-ping' sudah terdaftar di Hermes.")
                    return True

        # Create new job entry
        import uuid
        job_id = uuid.uuid4().hex[:12]
        new_job = {
            "id": job_id,
            "name": "wameow-ping",
            "prompt": "Ping heartbeat ke WhatsApp untuk memastikan semua sesi WA tetap terhubung. Eksekusi script wameow-ping.sh.",
            "skills": [],
            "skill": None,
            "model": None,
            "provider": None,
            "script": "wameow-ping.sh",
            "no_agent": True,
            "schedule": {
                "kind": "cron",
                "expr": "0 0 * * *",
                "display": "0 0 * * *"
            },
            "schedule_display": "0 0 * * *",
            "repeat": {"times": None, "completed": 0},
            "enabled": True,
            "state": "scheduled",
            "deliver": "local",
        }

        if isinstance(job_list, dict):
            job_list[job_id] = new_job
        elif isinstance(job_list, list):
            job_list.append(new_job)

        with open(jobs_file, "w") as f:
            json.dump(data, f, indent=2)

        print("✅ Berhasil mendaftarkan cronjob 'wameow-ping' ke Hermes cron (Setiap hari 00:00 WIB).")
        return True
    except Exception as e:
        print(f"⚠️ Gagal mendaftarkan ke Hermes cron secara langsung: {e}")
        return False


def register_linux_crontab():
    cron_entry = f"0 0 * * * {PING_SCRIPT_PATH} >> ~/.hermes/logs/wameow_ping.log 2>&1"
    try:
        existing = subprocess.run(["crontab", "-l"], capture_output=True, text=True).stdout
        if "wameow-ping.sh" in existing:
            print("ℹ️  Jadwal ping sudah ada di sistem crontab Linux.")
            return True

        new_crontab = existing.strip() + "\n" + cron_entry + "\n"
        subprocess.run(["crontab", "-"], input=new_crontab, text=True, check=True)
        print("✅ Berhasil menambahkan jadwal ping ke crontab Linux (0 0 * * * / Setiap hari 00:00 WIB).")
        return True
    except Exception as e:
        print(f"⚠️ Gagal mendaftarkan ke Linux crontab: {e}")
        return False


def main():
    parser = argparse.ArgumentParser(description="Setup WhatsApp Keep-Alive Ping")
    parser.add_argument("--auto", action="store_true", help="Jalankan otomatis tanpa prompt interaktif")
    parser.add_argument("--target-jid", help="JID tujuan ping (contoh: 120363...g.us atau 628...@s.whatsapp.net)")
    args = parser.parse_args()

    print("\n=======================================================")
    print("📡 WAMEOW WHATSAPP KEEP-ALIVE HEARTBEAT SETUP")
    print("=======================================================")
    print("Mencegah sesi WhatsApp logout/terputus secara otomatis.")
    print("Jadwal standar: Setiap jam 00:00 malam WIB (0 0 * * *).\n")

    # 1. Cek koneksi wameow
    sessions = []
    has_connected = False
    try:
        sessions = fetch_api("/sessions")
        print(f"Ditemukan {len(sessions)} sesi di Wameow:")
        for s in sessions:
            st = s.get("status")
            if st == "connected":
                has_connected = True
            badge = "🟢" if st == "connected" else "🔴"
            print(f"  {badge} Sesi: {s.get('name')} | Status: {st}")
    except Exception as e:
        print(f"ℹ️  Wameow belum dapat dihubungi di {WAMEOW_URL}: {e}")
        print("   (Script ping dan cronjob tetap akan disiapkan terlebih dahulu)")

    if not has_connected and len(sessions) > 0:
        first_session = sessions[0].get("name", "wa1")
        print(f"\n⚠️  Sesi WhatsApp belum terhubung. Silakan scan QR code di browser:")
        print(f"   👉 http://localhost:52135/scan/{first_session}")
        print("   Setelah terhubung, Anda dapat memilih grup tujuan atau chat ke diri sendiri.")

    # 2. Edukasi Opsi Target Ping
    print("\n💡 PANDUAN TUJUAN PENGIRIMAN PING:")
    print("Agar tidak mengganggu orang lain, sinyal ping sebaiknya diarahkan ke:")
    print("1. Grup Khusus (Recommended):")
    print("   Buat grup baru di WhatsApp (contoh: 'Ping Connection' atau 'Bot Logs'),")
    print("   masukkan bot ke grup tersebut, lalu ambil ID grupnya.")
    print("2. Chat ke Diri Sendiri (Self-Chat):")
    print("   Gunakan nomor bot/sendiri dalam format: <nomor_wa>@s.whatsapp.net\n")

    # 3. Buat script ping
    create_ping_script()

    # 4. Uji coba ping
    print("\n🧪 Menjalankan uji coba pengiriman ping...")
    res = test_ping()
    if res.get("status") == "ok":
        print(f"🎉 SUKSES! Ping berhasil dikirim: {res.get('sent', res)}")
    else:
        print(f"⚠️ Catatan respon ping: {res.get('message', res)}")
        print("  (Jika target grup/nomor belum disetel di flag Wameow -ping-group,")
        print("   Wameow akan menggunakan default atau JID yang telah Anda tentukan).")

    # 5. Daftarkan cronjob
    print("\n⏰ Mendaftarkan jadwal otomatis jam 00:00 WIB...")
    if not register_hermes_cron():
        register_linux_crontab()

    print("\n=======================================================")
    print("✅ Setup Keep-Alive Selesai!")
    print("Sesi WhatsApp Anda kini akan dijaga aktif secara otomatis.")
    print("=======================================================\n")


if __name__ == "__main__":
    main()
